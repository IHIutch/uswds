#!/usr/bin/env node
// Classify every +/- line in min-diffs/*.diff by change category,
// grouped by component and sorted by count. Writes a markdown report.
import fs from "node:fs";
import path from "node:path";

const diffDir = process.argv[2];
const outPath = process.argv[3];
if (!diffDir || !outPath) {
  console.error("usage: classify-by-component.mjs <min-diffs-dir> <out-file>");
  process.exit(1);
}

const rules = [
  {
    name: "Vendor prefix dropped",
    test: (l, side) =>
      side === "-" &&
      /^-(moz-|o-|webkit-appearance|webkit-mask-position: center center|webkit-mask-repeat)/.test(l),
  },
  {
    name: "Vendor prefix value normalized",
    test: (l, side) => side === "+" && /^-webkit-mask/.test(l),
  },
  {
    name: "Media query range syntax",
    test: (l) => /^@media[^{]*\bwidth\s*[<>]=/.test(l),
  },
  {
    name: "Media query legacy syntax",
    test: (l) => /^@media[^{]*\b(min|max)-width:/.test(l),
  },
  {
    name: "Pseudo-element :: → :",
    test: (l, side) => side === "+" && /:(after|before)\b/.test(l) && !/::(after|before)/.test(l),
  },
  {
    name: "Pseudo-element ::after / ::before",
    test: (l, side) => side === "-" && /::(after|before)\b/.test(l),
  },
  {
    name: "Color: rgba()/rgb() removed",
    test: (l, side) => side === "-" && /\brgba?\(/.test(l),
  },
  {
    name: "Color: 8-digit hex (#RRGGBBAA) added",
    test: (l, side) => side === "+" && /#[0-9a-f]{8}\b/i.test(l),
  },
  {
    name: "Color: named removed",
    test: (l, side) =>
      side === "-" && /:\s*(white|black|red|blue|green|gray|grey|transparent)\b/i.test(l),
  },
  {
    name: "Color: 3/6-digit hex added",
    test: (l, side) => side === "+" && /:\s*#[0-9a-f]{3,6}\b/i.test(l),
  },
  {
    name: "Position: center center → 50%",
    test: (l) => /:\s*(center\s+center|50%\s+50%)\b/.test(l),
  },
  {
    name: "Zero-with-unit (0px/0rem/0em)",
    test: (l) => /\b0(px|rem|em)\b/.test(l),
  },
  {
    name: "url() quoting change",
    test: (l) => /\burl\(/.test(l),
  },
  {
    name: "@font-face font-family quote change",
    test: (l) => /font-family:\s*["']?[A-Z]/.test(l),
  },
  {
    name: "@charset / banner comment",
    test: (l) => /^(@charset|\/\*!? uswds)/.test(l),
  },
  {
    name: "Selector / rule head",
    test: (l) => /[,{]\s*$/.test(l),
  },
  {
    name: "Rule close brace",
    test: (l) => l === "}",
  },
  {
    name: "Declaration reordering / formatting",
    test: () => true,
  },
];

function classify(line, side) {
  for (const r of rules) if (r.test(line, side)) return r.name;
  return "Declaration reordering / formatting";
}

// Collect: per-component counts
const perComponent = [];
const files = fs
  .readdirSync(diffDir)
  .filter((f) => f.endsWith(".diff") && f !== "_missing.diff");
for (const f of files.sort()) {
  const lines = fs.readFileSync(path.join(diffDir, f), "utf8").split("\n");
  const counts = new Map();
  let total = 0;
  for (const line of lines) {
    if (line.startsWith("---") || line.startsWith("+++")) continue;
    if (line.startsWith("@@")) continue;
    const trimmed = line.slice(1).trim();
    if (!trimmed) continue;
    let side;
    if (line.startsWith("-")) side = "-";
    else if (line.startsWith("+")) side = "+";
    else continue;
    const cat = classify(trimmed, side);
    counts.set(cat, (counts.get(cat) || 0) + 1);
    total++;
  }
  perComponent.push({
    name: f.replace(/\.diff$/, ""),
    total,
    counts: [...counts.entries()].sort((a, b) => b[1] - a[1]),
  });
}

perComponent.sort((a, b) => b.total - a.total);

// Emit markdown
const out = [];
out.push("");
out.push("");
out.push("# lightningcss migration — per-component change breakdown");
out.push("");
out.push(
  "For each component with a non-zero min-file diff, the table below " +
  "lists every change category with its line count. Components are " +
  "sorted by total changed lines, descending; within each component, " +
  "categories are sorted by count, descending.",
);
out.push("");
out.push(
  "Generated by `lightningcss-migration-artifacts/classify-by-component.mjs` " +
  "from `lightningcss-migration-artifacts/min-diffs/`. See " +
  "`lightningcss-migration-notes.md` for an explanation of each category.",
);
out.push("");

const zero = perComponent.filter((c) => c.total === 0);
const nonZero = perComponent.filter((c) => c.total > 0);

if (zero.length) {
  out.push(`## Components with byte-identical output (${zero.length})`);
  out.push("");
  for (const c of zero) out.push(`- \`${c.name}\``);
  out.push("");
}

out.push(`## Components with changes (${nonZero.length})`);
out.push("");

for (const c of nonZero) {
  out.push(`### \`${c.name}\` — ${c.total} lines`);
  out.push("");
  out.push("| Lines | Category |");
  out.push("|---:|---|");
  for (const [cat, n] of c.counts) {
    out.push(`| ${String(n).padStart(5)} | ${cat} |`);
  }
  out.push("");
}

fs.writeFileSync(outPath, out.join("\n"));
console.log(`wrote ${outPath} (${nonZero.length} components with changes, ${zero.length} unchanged)`);
